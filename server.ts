import 'dotenv/config';
import express from 'express';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ExternalMlHttpProvider } from './server/models/externalMlAdapter.ts';
import { PhysicsBaselineProvider } from './server/models/heuristicBaselineProvider.ts';
import { ModelRegistry } from './server/models/inferenceProvider.ts';
import { createAnalyzeRouter } from './server/routes/analyze.ts';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function startServer() {
  const app = express();
  const port = Number(process.env.PORT) || 3000;

  app.use(express.json({ limit: '15mb' }));

  // Register inference providers in modular registry
  const registry = new ModelRegistry();
  registry.register(new PhysicsBaselineProvider(), true);
  registry.register(new ExternalMlHttpProvider(), false);

  // Mount versioned/modular API routes
  app.use('/api', createAnalyzeRouter(registry));

  const isProd = process.env.NODE_ENV === 'production';

  if (!isProd) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distDir = path.resolve(__dirname, 'dist');
    if (fs.existsSync(distDir)) {
      app.use(express.static(distDir));
      app.get('/{*splat}', (_req, res) => {
        res.sendFile(path.join(distDir, 'index.html'));
      });
    }
  }

  app.listen(port, '0.0.0.0', () => {
    console.log(`Fault Analyzer server running on http://0.0.0.0:${port}`);
  });
}

startServer().catch((err) => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
