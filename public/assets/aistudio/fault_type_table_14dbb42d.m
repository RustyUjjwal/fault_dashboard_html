%% fault_type_table.m
%
% Canonical fault-type list for v11 (call this from the sweep/extractor
% script). Split into its OWN file, matching its own function name, on
% purpose: MATLAB cannot call a local function (one buried inside another
% .m file, like it was previously nested inside v11_fault_injection_core.m)
% from outside that file - only the file's own top-level function is
% externally visible. The original nested version would have failed the
% first time the extractor actually ran it, since it was never tested in
% real MATLAB. See severity_range_for_mechanism.m and mechanism_to_RV.m
% for the same fix applied to the other two sweep-helper functions.
%
% Each row: {label, mechanism, G, A, B, C}
%
% ShortCircuit rows (11) carry the Kaggle-style phase/ground combos -
% LG/LL/LLG repeated for all three phase pairs, plus LLL and LLLG. All 11
% share mechanism='ShortCircuit' (short-circuit-CATEGORY grouping - note
% only LLL/LLLG are actually "symmetrical" in the strict power-systems
% sense; LG/LL/LLG are unsymmetrical. Don't conflate the two claims in
% your report).
%
% The four non-short-circuit mechanisms (Overcurrent/Overvoltage/
% Undervoltage/OpenCircuit) don't have a "which lines touch which" shape
% the way a short circuit does - a broken conductor or an overload is a
% per-conductor condition, not a contact event - so each gets 3 single-
% phase rows (A/B/C) plus 1 three-phase-symmetric row (ABC together).
% G is always 0 for these (no ground-contact semantics; matches v8, which
% never had a G flag at all).
function T = fault_type_table()
    T = { ...
        'Healthy', 'Healthy', 0, 0, 0, 0; ...
        ...
        'LG_A',    'ShortCircuit', 1, 1, 0, 0; ...
        'LG_B',    'ShortCircuit', 1, 0, 1, 0; ...
        'LG_C',    'ShortCircuit', 1, 0, 0, 1; ...
        'LL_AB',   'ShortCircuit', 0, 1, 1, 0; ...
        'LL_BC',   'ShortCircuit', 0, 0, 1, 1; ...
        'LL_CA',   'ShortCircuit', 0, 1, 0, 1; ...
        'LLG_AB',  'ShortCircuit', 1, 1, 1, 0; ...
        'LLG_BC',  'ShortCircuit', 1, 0, 1, 1; ...
        'LLG_CA',  'ShortCircuit', 1, 1, 0, 1; ...
        'LLL',     'ShortCircuit', 0, 1, 1, 1; ...
        'LLLG',    'ShortCircuit', 1, 1, 1, 1; ...
        ...
        'Overcurrent_A',   'Overcurrent', 0, 1, 0, 0; ...
        'Overcurrent_B',   'Overcurrent', 0, 0, 1, 0; ...
        'Overcurrent_C',   'Overcurrent', 0, 0, 0, 1; ...
        'Overcurrent_ABC', 'Overcurrent', 0, 1, 1, 1; ...
        ...
        'Overvoltage_A',   'Overvoltage', 0, 1, 0, 0; ...
        'Overvoltage_B',   'Overvoltage', 0, 0, 1, 0; ...
        'Overvoltage_C',   'Overvoltage', 0, 0, 0, 1; ...
        'Overvoltage_ABC', 'Overvoltage', 0, 1, 1, 1; ...
        ...
        'Undervoltage_A',   'Undervoltage', 0, 1, 0, 0; ...
        'Undervoltage_B',   'Undervoltage', 0, 0, 1, 0; ...
        'Undervoltage_C',   'Undervoltage', 0, 0, 0, 1; ...
        'Undervoltage_ABC', 'Undervoltage', 0, 1, 1, 1; ...
        ...
        'OpenCircuit_A',   'OpenCircuit', 0, 1, 0, 0; ...
        'OpenCircuit_B',   'OpenCircuit', 0, 0, 1, 0; ...
        'OpenCircuit_C',   'OpenCircuit', 0, 0, 0, 1; ...
        'OpenCircuit_ABC', 'OpenCircuit', 0, 1, 1, 1; ...
    };
    % 1 Healthy + 11 ShortCircuit + 4 mechanisms x 4 rows = 28 fault-type rows.
end
